# Without a cap an adversarial tie could explode the search; two orderings already
# prove ambiguity, so the search stops there.
_AMBIGUITY_CAP = 2


class LegacyChainError(RuntimeError):
    """A trip's existing substitutions cannot be migrated without guessing."""


class LegacyLink(NamedTuple):
    id: uuid.UUID
    outgoing_driver_id: uuid.UUID
    incoming_driver_id: uuid.UUID
    at: datetime


def _find_orderings(
    original_driver_id: uuid.UUID, links: list[LegacyLink], *, check_time: bool,
) -> list[list[LegacyLink]]:
    """Every ordering that uses all links (up to the cap), found depth-first."""
    found: list[list[LegacyLink]] = []
    path: list[LegacyLink] = []

    def walk(holder: uuid.UUID, last_at: datetime | None, remaining: list[LegacyLink]) -> None:
        if len(found) >= _AMBIGUITY_CAP:
            return
        if not remaining:
            found.append(list(path))
            return
        for link in remaining:
            if link.outgoing_driver_id != holder:
                continue
            if check_time and last_at is not None and link.at < last_at:
                continue
            path.append(link)
            walk(link.incoming_driver_id, link.at, [r for r in remaining if r.id != link.id])
            path.pop()

    walk(original_driver_id, None, links)
    return found


def order_legacy_chain(
    *, trip_id: uuid.UUID, original_driver_id: uuid.UUID, links: list[LegacyLink],
) -> list[LegacyLink]:
    """The one valid ordering of a trip's legacy substitutions, or LegacyChainError."""
    if any(link.outgoing_driver_id == link.incoming_driver_id for link in links):
        raise LegacyChainError(f"trip {trip_id}: a legacy substitution hands the trip to itself")

    with_time = _find_orderings(original_driver_id, links, check_time=True)
    if len(with_time) == 1:
        return with_time[0]
    if len(with_time) > 1:
        raise LegacyChainError(
            f"trip {trip_id}: legacy substitution chain is ambiguous (equal timestamps allow more "
            "than one ordering); UUID order is not evidence of custody"
        )

    without_time = _find_orderings(original_driver_id, links, check_time=False)
    if without_time:
        raise LegacyChainError(
            f"trip {trip_id}: legacy substitution chronology contradicts the only possible chain order"
        )
    raise LegacyChainError(
        f"trip {trip_id}: legacy substitution chain does not continue from the original driver "
        f"{original_driver_id} (every outgoing driver must be the previous incoming driver)"
    )


def _plan_legacy_sequences(bind: sa.engine.Connection) -> list[tuple[uuid.UUID, int, uuid.UUID | None]]:
    """Validate every trip's legacy chain; return (row id, sequence, previous id) for all rows."""
    rows = bind.execute(sa.text(
        "SELECT s.id, s.trip_id, s.original_driver_id, s.substituting_driver_id, s.substitution_at, "
        "t.driver_id AS trip_driver_id FROM driver_substitutions s JOIN trips t ON t.id = s.trip_id"
    )).all()
    by_trip: dict[uuid.UUID, list[LegacyLink]] = defaultdict(list)
    original_driver: dict[uuid.UUID, uuid.UUID] = {}
    for row in rows:
        by_trip[row.trip_id].append(LegacyLink(row.id, row.original_driver_id, row.substituting_driver_id, row.substitution_at))
        original_driver[row.trip_id] = row.trip_driver_id

    plan: list[tuple[uuid.UUID, int, uuid.UUID | None]] = []
    for trip_id in sorted(by_trip):
        ordered = order_legacy_chain(
            trip_id=trip_id, original_driver_id=original_driver[trip_id], links=by_trip[trip_id],
        )
        previous: uuid.UUID | None = None
        for position, link in enumerate(ordered, start=1):
            plan.append((link.id, position, previous))
            previous = link.id
    return plan


